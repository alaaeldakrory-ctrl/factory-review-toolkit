"""Queue a Kit render job (the running Kit's job runner picks it up): open a USD, then capture stills and / or a
frame sequence from given cameras. Stills are path traced, sequences real time.

    python tools/kit_render.py JOBNAME scene.usd out_dir shots.json
    shots.json: [{"name": "a.png", "eye": [x,y,z], "at": [x,y,z], "mm": 30, "frame": 0},
                 {"seq": "track", "eye": [...], "at": [...], "eye_end": [...], "at_end": [...], "frames": [0, 120, 1]},
                 {"name": "hero.png", "camera": "/World/Studio/Hero"},
                 {"seq": "turn", "eye": [...], "at": [...], "mm": 30, "frames": [0, 240, 3]}]
"""
import json
import os
import sys

JOBS = r"C:\OmniverseData\kit_jobs"
TEMPLATE = r'''# generated by tools/kit_render.py
import os

import carb
import omni.kit.app
import omni.timeline as TL
import omni.usd
from pxr import UsdGeom

ROOT = r"{root}"
SCENE = r"{scene}"
OUT = r"{out}"
SHOTS = {shots!r}


async def frames(n):
    for _ in range(n):
        await omni.kit.app.get_app().next_update_async()


async def run(log):
    em = omni.kit.app.get_app().get_extension_manager()
    em.add_path(ROOT.replace("\\\\", "/") + "/exts")
    for ext in ("frt.core", "frt.scene"):
        em.set_extension_enabled_immediate(ext, True)
    await frames(10)
    from frt_scene import window as W
    from omni.kit.viewport.utility import capture_viewport_to_file, get_active_viewport
    ctx = omni.usd.get_context()
    s = carb.settings.get_settings()
    for k in ("/app/viewport/grid/enabled",                  # session only - never persistent settings
              "/app/renderer/skipWhileMinimized"):          # keep rendering when the window is minimized
        s.set(k, False)
    vp = None
    for _ in range(600):                                   # Kit may still be starting: wait for a live viewport
        try:
            vp = get_active_viewport()
            if vp is not None and vp.resolution:
                break
        except Exception:
            vp = None
        await frames(10)
    await ctx.new_stage_async()
    await frames(10)
    await ctx.open_stage_async(SCENE)
    await frames(350)
    os.makedirs(OUT, exist_ok=True)

    def mode(pt):
        if pt:
            s.set("/rtx/rendermode", "PathTracing")
            s.set("/rtx/pathtracing/spp", 4)
            s.set("/rtx/pathtracing/totalSpp", 160)
            s.set("/rtx/pathtracing/optixDenoiser/enabled", True)
        else:
            s.set("/rtx/rendermode", "RaytracedLighting")

    def aim(sh):
        if sh.get("camera"):
            vp.camera_path = sh["camera"]
            return
        vp.camera_path = "/OmniverseKit_Persp"
        cam = ctx.get_stage().GetPrimAtPath("/OmniverseKit_Persp")
        UsdGeom.Camera(cam).GetFocalLengthAttr().Set(float(sh.get("mm", 24)))
        W.look_at(tuple(sh["eye"]), tuple(sh["at"]))

    async def grab(path, settle):
        await frames(settle)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        cap = capture_viewport_to_file(vp, path)
        if hasattr(cap, "wait_for_result"):
            await cap.wait_for_result(completion_frames=20)
        return os.path.exists(path)
    try:
        for sh in SHOTS:
            if "seq" in sh:
                mode(False)
                aim(sh)
                a, b, step = sh["frames"]
                n = 0
                for k, f in enumerate(range(a, b + 1, step)):
                    TL.get_timeline_interface().set_current_time(f / 24.0)
                    if sh.get("eye_end"):                  # tracking shot: eye / target move linearly over the sequence
                        u = (f - a) / max(b - a, 1)
                        e = [x0 + (x1 - x0) * u for x0, x1 in zip(sh["eye"], sh["eye_end"])]
                        t_ = [x0 + (x1 - x0) * u for x0, x1 in zip(sh["at"], sh["at_end"])]
                        W.look_at(tuple(e), tuple(t_))
                    n += await grab(os.path.join(OUT, sh["seq"], f"f{{k:03d}}.png"), 8)
                log(f"{{sh['seq']}}: {{n}} frames")
            else:
                mode(True)
                TL.get_timeline_interface().set_current_time(sh.get("frame", 0) / 24.0)
                aim(sh)
                log(f"{{sh['name']}}: {{await grab(os.path.join(OUT, sh['name']), sh.get('settle', 150))}}")
    finally:
        mode(False)
        vp.camera_path = "/OmniverseKit_Persp"
        TL.get_timeline_interface().set_current_time(0.0)
    log("done")
'''


def queue(name, scene, out, shots):
    root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    src = TEMPLATE.format(root=root, scene=os.path.abspath(scene), out=os.path.abspath(out), shots=shots)
    for ext in (".done", ".failed", ".log"):
        p = os.path.join(JOBS, name + ext)
        if os.path.exists(p):
            os.remove(p)
    with open(os.path.join(JOBS, name + ".py"), "w", encoding="utf-8") as f:
        f.write(src)
    return os.path.join(JOBS, name + ".py")


if __name__ == "__main__":
    name, scene, out, shots = sys.argv[1:5]
    with open(shots) as f:
        print("queued", queue(name, scene, out, json.load(f)))
